/**
 * Insert or replace our marked section in a shared file, leaving everything else untouched. Returns the new text,
 * or undefined when it is already current.
 */
export function upsertSection(existing: string | undefined, section: string): string | undefined {
  const text = existing ?? '';
  const start = text.indexOf(SECTION_START);
  const end = text.indexOf(SECTION_END, start + 1);
  let next: string;
  if (start !== -1 && end !== -1) {
    const after = text.slice(end + SECTION_END.length).replace(/^\r?\n/, '');
    next = text.slice(0, start) + section + after;
  } else {
    next = text.trim() ? text.replace(/\s*$/, '\n\n') + section : section;
  }
  return next === text ? undefined : next;
}

/** New content for a harness file given what is on disk (undefined = nothing to write). */
export function renderInstall(h: Harness, body: string, version: string, existing: string | undefined): string | undefined {
  const content = h.render(body, version);
  if (h.mode === 'section') return upsertSection(existing, content);
  return existing === content ? undefined : content;
}

const MARKER = /<!-- Generated by VS Canvas(?: (\S+?))?\. Run "VS Canvas: Install Agent Skills"/;

/**
 * The version stamped in a generated file (inside our marked block for shared files): the version string,
 * '0.0.0' for an older unstamped marker, undefined when there is no marker (not managed by VS Canvas).
 */
export function installedVersion(text: string): string | undefined {
  const start = text.indexOf(SECTION_START);
  const end = start === -1 ? -1 : text.indexOf(SECTION_END, start + 1);
  const scope = start !== -1 && end !== -1 ? text.slice(start, end) : text;
  const m = MARKER.exec(scope);
  return m ? (m[1] ?? '0.0.0') : undefined;
}

/** major.minor.patch as numbers (prerelease and build suffixes ignored); undefined when it does not parse. */
function semver(v: string): [number, number, number] | undefined {
  const m = /^v?(\d+)\.(\d+)\.(\d+)/.exec(v);
  return m ? [Number(m[1]), Number(m[2]), Number(m[3])] : undefined;
}

/** True when `a` is strictly older than `b`. An unparseable `a` counts as oldest, an unparseable `b` as unknown. */
function isOlder(a: string, b: string): boolean {
  const y = semver(b);
  if (!y) return false;
  const x = semver(a) ?? [0, 0, 0];
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] < y[i];
  return false;
}

/**
 * New content for an already-installed guide, or undefined (nothing to write). Only files VS Canvas manages are
 * refreshed, and only when the version they were written by is older than the running one: a missing file is never
 * created, a file without our marker is never touched, and the same or a newer version is left alone (so teammates on
 * different versions do not fight over a committed file).
 */
export function renderRefresh(h: Harness, body: string, version: string, existing: string | undefined): string | undefined {
  if (existing === undefined) return undefined;
  const installed = installedVersion(existing);
  if (installed === undefined || !isOlder(installed, version)) return undefined;
  return renderInstall(h, body, version, existing);
}

export type RefreshIO = {
  /** Directory the harness path is relative to, or undefined when unavailable (e.g. no workspace folder). */
  root: (h: Harness) => string | undefined;
  read: (path: string) => Promise<string | undefined>;
  write: (path: string, text: string) => Promise<void>;
};

/** Refresh every installed harness file. Never throws: failures are reported per file and the rest still run. */
export async function refreshAll(
  body: string,
  version: string,
  io: RefreshIO,
): Promise<{ updated: string[]; failed: { path: string; error: string }[] }> {
  const updated: string[] = [];
  const failed: { path: string; error: string }[] = [];
  for (const h of HARNESSES) {
    let file = h.path;
    try {
      const root = io.root(h);
      if (!root) continue;
      file = path.join(root, ...h.path.split('/'));
      const next = renderRefresh(h, body, version, await io.read(file));
      if (next === undefined) continue;
      await io.write(file, next);
      updated.push(file);
    } catch (e) {
      failed.push({ path: file, error: e instanceof Error ? e.message : String(e) });
    }
  }
  return { updated, failed };
}
