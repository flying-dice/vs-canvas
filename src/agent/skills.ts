/** Marker stamped into every generated file; carries the extension version that wrote it. */
export const GENERATED = (version: string) =>
  `<!-- Generated by VS Canvas ${version}. Run "VS Canvas: Install Agent Skills" to update. -->`;
export const SECTION_START = '<!-- vs-canvas:start -->';
export const SECTION_END = '<!-- vs-canvas:end -->';

const frontmatter = (fields: Record<string, string>) =>
  '---\n' + Object.entries(fields).map(([k, v]) => `${k}: ${v}`).join('\n') + '\n---\n\n';

const quote = (s: string) => JSON.stringify(s);

/** Push every markdown heading down one level (the guide becomes a `##` section inside AGENTS.md etc.). */
export function demoteHeadings(md: string): string {
  let fence = false;
  return md
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) fence = !fence;
      return !fence && /^#{1,5} /.test(line) ? '#' + line : line;
    })
    .join('\n');
}

const asFile = (head: string, body: string, version: string) => head + GENERATED(version) + '\n\n' + body.trim() + '\n';
const asSection = (body: string, version: string) =>
  `${SECTION_START}\n${GENERATED(version)}\n\n${demoteHeadings(body.trim())}\n${SECTION_END}\n`;

