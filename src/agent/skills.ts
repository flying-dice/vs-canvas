export type HarnessId =
  | 'claude-project'
  | 'claude-user'
  | 'copilot'
  | 'cursor'
  | 'windsurf'
  | 'cline'
  | 'agents-md'
  | 'gemini';

export type Harness = {
  id: HarnessId;
  label: string;
  detail: string;
  /** 'workspace' paths are relative to the first workspace folder; 'user' paths to the home directory. */
  scope: 'workspace' | 'user';
  path: string;
  /** 'file' = a file we own (overwritten); 'section' = a marked section inside a shared file (upserted). */
  mode: 'file' | 'section';
  /** Paths (same scope) whose presence suggests the harness is in use, so the installer preselects it. */
  detect: string[];
  render: (body: string, version: string) => string;
};

